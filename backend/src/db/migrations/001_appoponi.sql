CREATE OR REPLACE FUNCTION appoponi_require_member_account()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  actual_type TEXT;
BEGIN
  SELECT account_type
  INTO actual_type
  FROM accounts
  WHERE id = NEW.account_id;

  IF actual_type IS DISTINCT FROM 'member' THEN
    RAISE EXCEPTION 'MEMBER_ACCOUNT_REQUIRED';
  END IF;

  RETURN NEW;
END;
$$;


CREATE TRIGGER household_members_require_member_account
BEFORE INSERT OR UPDATE OF account_id
ON household_members
FOR EACH ROW
EXECUTE FUNCTION appoponi_require_member_account();


CREATE TRIGGER event_registrations_require_member_account
BEFORE INSERT OR UPDATE OF account_id
ON event_registrations
FOR EACH ROW
EXECUTE FUNCTION appoponi_require_member_account();


CREATE OR REPLACE FUNCTION appoponi_require_staff_account()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  actual_type TEXT;
BEGIN
  IF NEW.account_id IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT account_type
  INTO actual_type
  FROM accounts
  WHERE id = NEW.account_id;

  IF actual_type IS NULL
     OR actual_type NOT IN ('staff', 'admin')
  THEN
    RAISE EXCEPTION 'STAFF_ACCOUNT_REQUIRED';
  END IF;

  RETURN NEW;
END;
$$;


CREATE TRIGGER staff_members_require_staff_account
BEFORE INSERT OR UPDATE OF account_id
ON staff_members
FOR EACH ROW
EXECUTE FUNCTION appoponi_require_staff_account();


CREATE OR REPLACE FUNCTION appoponi_protect_account_type()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.account_type = OLD.account_type THEN
    RETURN NEW;
  END IF;

  IF NEW.account_type <> 'member'
     AND (
       EXISTS (
         SELECT 1
         FROM household_members
         WHERE account_id = OLD.id
       )
       OR EXISTS (
         SELECT 1
         FROM event_registrations
         WHERE account_id = OLD.id
       )
     )
  THEN
    RAISE EXCEPTION 'ACCOUNT_HAS_MEMBER_DATA';
  END IF;

  IF NEW.account_type NOT IN ('staff', 'admin')
     AND EXISTS (
       SELECT 1
       FROM staff_members
       WHERE account_id = OLD.id
     )
  THEN
    RAISE EXCEPTION 'ACCOUNT_HAS_STAFF_PROFILE';
  END IF;

  RETURN NEW;
END;
$$;


CREATE TRIGGER protect_account_type
BEFORE UPDATE OF account_type
ON accounts
FOR EACH ROW
EXECUTE FUNCTION appoponi_protect_account_type();


/* ============================================================
   EXACTLY ONE PRIMARY PROFILE PER POPULATED HOUSEHOLD ACCOUNT
   ============================================================ */

CREATE OR REPLACE FUNCTION appoponi_assert_household_primary(
  target_account_id BIGINT
)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
  member_count BIGINT;
  primary_count BIGINT;
BEGIN
  SELECT
    COUNT(*),
    COUNT(*) FILTER (
      WHERE member_role = 'primary'
    )
  INTO
    member_count,
    primary_count
  FROM household_members
  WHERE account_id = target_account_id;

  IF member_count > 0
     AND primary_count <> 1
  THEN
    RAISE EXCEPTION 'HOUSEHOLD_PRIMARY_REQUIRED';
  END IF;
END;
$$;


CREATE OR REPLACE FUNCTION appoponi_enforce_household_primary()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    PERFORM appoponi_assert_household_primary(
      NEW.account_id
    );

  ELSIF TG_OP = 'DELETE' THEN
    PERFORM appoponi_assert_household_primary(
      OLD.account_id
    );

  ELSE
    PERFORM appoponi_assert_household_primary(
      NEW.account_id
    );

    IF OLD.account_id IS DISTINCT FROM NEW.account_id THEN
      PERFORM appoponi_assert_household_primary(
        OLD.account_id
      );
    END IF;
  END IF;

  RETURN NULL;
END;
$$;


CREATE CONSTRAINT TRIGGER household_members_primary_required
AFTER INSERT OR UPDATE OR DELETE
ON household_members
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION appoponi_enforce_household_primary();


/* ============================================================
   EVENT CHILD TIMES MUST FIT INSIDE EVENT
   ============================================================ */

CREATE OR REPLACE FUNCTION appoponi_validate_event_child_time()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  parent_start TIMESTAMPTZ;
  parent_end TIMESTAMPTZ;
BEGIN
  SELECT
    starts_at,
    ends_at
  INTO
    parent_start,
    parent_end
  FROM events
  WHERE id = NEW.event_id;

  IF NEW.starts_at < parent_start
     OR NEW.ends_at > parent_end
  THEN
    RAISE EXCEPTION 'EVENT_TIME_OUTSIDE_EVENT';
  END IF;

  RETURN NEW;
END;
$$;


CREATE TRIGGER event_activities_inside_event
BEFORE INSERT OR UPDATE OF event_id, starts_at, ends_at
ON event_activities
FOR EACH ROW
EXECUTE FUNCTION appoponi_validate_event_child_time();


CREATE TRIGGER event_meals_inside_event
