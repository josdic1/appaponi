$$;


/* ============================================================
   GLOBAL IMMUTABLE AUDIT LOG
   ============================================================ */

CREATE TABLE audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  table_name TEXT NOT NULL,
  row_id TEXT NOT NULL,

  action TEXT NOT NULL
    CHECK (
      action IN (
        'INSERT',
        'UPDATE',
        'DELETE'
      )
    ),

  old_values JSONB,
  new_values JSONB,

  actor_account_id BIGINT,

  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


CREATE OR REPLACE FUNCTION appoponi_audit_row_change()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  actor_text TEXT;
  actor_id BIGINT;
  row_json JSONB;
  changed_row_id TEXT;
BEGIN
  actor_text :=
    current_setting(
      'appoponi.actor_account_id',
      true
    );

  IF actor_text IS NOT NULL
     AND actor_text ~ '^[0-9]+$'
  THEN
    actor_id := actor_text::BIGINT;
  ELSE
    actor_id := NULL;
  END IF;

  IF TG_OP = 'DELETE' THEN
    row_json := to_jsonb(OLD);
  ELSE
    row_json := to_jsonb(NEW);
  END IF;

  changed_row_id := COALESCE(
    row_json->>'id',
    row_json->>'account_id',
    row_json->>'name',
    'unknown'
  );

  INSERT INTO audit_log (
    table_name,
    row_id,
    action,
    old_values,
    new_values,
    actor_account_id
  )
  VALUES (
    TG_TABLE_NAME,
    changed_row_id,
    TG_OP,
    CASE
      WHEN TG_OP IN ('UPDATE', 'DELETE')
      THEN to_jsonb(OLD)
      ELSE NULL
    END,
    CASE
      WHEN TG_OP IN ('INSERT', 'UPDATE')
      THEN to_jsonb(NEW)
      ELSE NULL
    END,
    actor_id
  );

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;

  RETURN NEW;
END;
$$;


DO $$
DECLARE
  target_table TEXT;
BEGIN
  FOR target_table IN
    SELECT tablename
    FROM pg_tables
    WHERE schemaname = 'public'
      AND tablename NOT IN (
        'audit_log',
        'appoponi_migrations'
      )
  LOOP
    EXECUTE format(
      'CREATE TRIGGER audit_row_change
       AFTER INSERT OR UPDATE OR DELETE ON %I
       FOR EACH ROW
       EXECUTE FUNCTION appoponi_audit_row_change()',
      target_table
    );
  END LOOP;
END;
$$;


CREATE OR REPLACE FUNCTION appoponi_prevent_audit_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  RAISE EXCEPTION
    'audit_log is append-only';
END;
$$;


CREATE TRIGGER audit_log_no_update_delete
BEFORE UPDATE OR DELETE
ON audit_log
FOR EACH ROW
EXECUTE FUNCTION appoponi_prevent_audit_mutation();


CREATE TRIGGER audit_log_no_truncate
BEFORE TRUNCATE
ON audit_log
FOR EACH STATEMENT
EXECUTE FUNCTION appoponi_prevent_audit_mutation();
