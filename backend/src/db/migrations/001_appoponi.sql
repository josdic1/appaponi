/* ============================================================
   EVENT REGISTRATION CAPACITY
   ============================================================ */

CREATE OR REPLACE FUNCTION appoponi_enforce_registration_capacity()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  household_account_id BIGINT;
  paid_spots INTEGER;
  used_spots INTEGER;
BEGIN
  SELECT account_id
  INTO household_account_id
  FROM household_members
  WHERE id = NEW.member_id;

  PERFORM pg_advisory_xact_lock(
    household_account_id
  );

  SELECT spots_paid_for
  INTO paid_spots
  FROM event_registrations
  WHERE account_id = household_account_id
    AND event_id = NEW.event_id
  FOR UPDATE;

  IF paid_spots IS NULL THEN
    RAISE EXCEPTION 'EVENT_REGISTRATION_REQUIRED';
  END IF;

  SELECT COUNT(*)::INTEGER
  INTO used_spots
  FROM member_attendees ma
  JOIN household_members hm
    ON hm.id = ma.member_id
  WHERE hm.account_id = household_account_id
    AND ma.event_id = NEW.event_id
    AND (
      TG_OP = 'INSERT'
      OR ma.id <> NEW.id
    );

  IF used_spots >= paid_spots THEN
    RAISE EXCEPTION 'EVENT_REGISTRATION_SPOTS_FULL';
  END IF;

  RETURN NEW;
END;
$$;


CREATE TRIGGER member_attendees_registration_capacity
BEFORE INSERT OR UPDATE OF member_id, event_id
ON member_attendees
FOR EACH ROW
EXECUTE FUNCTION appoponi_enforce_registration_capacity();


CREATE OR REPLACE FUNCTION appoponi_protect_registration_capacity()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  selected_count INTEGER;
BEGIN
  SELECT COUNT(*)::INTEGER
  INTO selected_count
  FROM member_attendees ma
  JOIN household_members hm
    ON hm.id = ma.member_id
  WHERE hm.account_id = NEW.account_id
    AND ma.event_id = NEW.event_id;

  IF NEW.spots_paid_for < selected_count THEN
    RAISE EXCEPTION
      'EVENT_REGISTRATION_BELOW_SELECTED_ATTENDEES';
  END IF;

  RETURN NEW;
END;
$$;


CREATE TRIGGER event_registrations_capacity_guard
BEFORE UPDATE OF account_id, event_id, spots_paid_for
ON event_registrations
FOR EACH ROW
EXECUTE FUNCTION appoponi_protect_registration_capacity();


/* ============================================================
   MEMBER ACTIVITY SIGNUP RULES
   same event
   no duplicates
   no overlapping activity
   respect activity capacity
   ============================================================ */

CREATE OR REPLACE FUNCTION appoponi_enforce_activity_signup()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  requested_member_id BIGINT;
  attendee_event_id BIGINT;

  requested_event_id BIGINT;
  requested_start TIMESTAMPTZ;
  requested_end TIMESTAMPTZ;
  requested_capacity INTEGER;

  current_signup_id BIGINT;
  signup_count INTEGER;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    current_signup_id := OLD.id;
  ELSE
    current_signup_id := NULL;
  END IF;

  SELECT
    member_id,
    event_id
  INTO
    requested_member_id,
    attendee_event_id
  FROM member_attendees
  WHERE id = NEW.member_attendee_id;

  SELECT
    event_id,
    starts_at,
    ends_at,
    capacity
  INTO
    requested_event_id,
    requested_start,
    requested_end,
    requested_capacity
  FROM event_activities
  WHERE id = NEW.event_activity_id;

  IF attendee_event_id <> requested_event_id THEN
    RAISE EXCEPTION
      'ACTIVITY_SIGNUP_EVENT_MISMATCH';
  END IF;

  PERFORM pg_advisory_xact_lock(
    requested_member_id
  );

  PERFORM pg_advisory_xact_lock(
    NEW.event_activity_id
  );

  IF EXISTS (
    SELECT 1
    FROM event_activity_signups eas
    JOIN member_attendees ma
      ON ma.id = eas.member_attendee_id
    WHERE eas.event_activity_id = NEW.event_activity_id
      AND ma.member_id = requested_member_id
      AND (
        current_signup_id IS NULL
        OR eas.id <> current_signup_id
      )
  ) THEN
    RAISE EXCEPTION
      'ACTIVITY_SIGNUP_DUPLICATE';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM event_activity_signups eas
    JOIN member_attendees ma
      ON ma.id = eas.member_attendee_id
    JOIN event_activities existing_activity
      ON existing_activity.id = eas.event_activity_id
    WHERE ma.member_id = requested_member_id
      AND eas.event_activity_id <> NEW.event_activity_id
      AND (
        current_signup_id IS NULL
        OR eas.id <> current_signup_id
      )
      AND requested_start < existing_activity.ends_at
      AND requested_end > existing_activity.starts_at
  ) THEN
    RAISE EXCEPTION
      'ACTIVITY_TIME_CONFLICT';
  END IF;

  IF requested_capacity IS NOT NULL THEN
    SELECT COUNT(*)::INTEGER
    INTO signup_count
    FROM event_activity_signups
    WHERE event_activity_id = NEW.event_activity_id
      AND (
        current_signup_id IS NULL
        OR id <> current_signup_id
      );

    IF signup_count >= requested_capacity THEN
      RAISE EXCEPTION
        'ACTIVITY_CAPACITY_FULL';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;


CREATE TRIGGER enforce_activity_signup
BEFORE INSERT OR UPDATE
ON event_activity_signups
FOR EACH ROW
EXECUTE FUNCTION appoponi_enforce_activity_signup();


/* ============================================================
   STAFF SCHEDULE CONFLICTS
   ============================================================ */

CREATE OR REPLACE FUNCTION appoponi_enforce_staff_activity_schedule()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  requested_start TIMESTAMPTZ;
  requested_end TIMESTAMPTZ;
  current_assignment_id BIGINT;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    current_assignment_id := OLD.id;
  ELSE
    current_assignment_id := NULL;
  END IF;

  SELECT
    starts_at,
    ends_at
  INTO
    requested_start,
    requested_end
  FROM event_activities
  WHERE id = NEW.event_activity_id;

  PERFORM pg_advisory_xact_lock(
    NEW.staff_member_id
  );

  IF EXISTS (
    SELECT 1
    FROM event_activity_staff eas
    JOIN event_activities ea
      ON ea.id = eas.event_activity_id
    WHERE eas.staff_member_id = NEW.staff_member_id
      AND (
        current_assignment_id IS NULL
        OR eas.id <> current_assignment_id
      )
      AND requested_start < ea.ends_at
      AND requested_end > ea.starts_at
  ) THEN
    RAISE EXCEPTION
      'STAFF_ACTIVITY_TIME_CONFLICT';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM babysitting_requests br
    WHERE br.sitter_staff_member_id = NEW.staff_member_id
      AND br.status = 'confirmed'
      AND requested_start < br.ends_at
      AND requested_end > br.starts_at
  ) THEN
    RAISE EXCEPTION
      'STAFF_BABYSITTING_TIME_CONFLICT';
  END IF;

  RETURN NEW;
END;
$$;


CREATE TRIGGER enforce_staff_activity_schedule
BEFORE INSERT OR UPDATE
ON event_activity_staff
FOR EACH ROW
EXECUTE FUNCTION appoponi_enforce_staff_activity_schedule();


/* ============================================================
   BABYSITTING INTEGRITY
   ============================================================ */

CREATE OR REPLACE FUNCTION appoponi_validate_babysitting_request()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  event_start TIMESTAMPTZ;
  event_end TIMESTAMPTZ;
  sitter_allowed BOOLEAN;
  current_request_id BIGINT;
BEGIN
  SELECT
    e.starts_at,
    e.ends_at
  INTO
    event_start,
    event_end
  FROM event_registrations er
  JOIN events e
    ON e.id = er.event_id
  WHERE er.id = NEW.event_registration_id;

  IF NEW.starts_at < event_start
     OR NEW.ends_at > event_end
  THEN
    RAISE EXCEPTION
      'BABYSITTING_OUTSIDE_EVENT';
  END IF;

  IF NEW.sitter_staff_member_id IS NULL
     OR NEW.status <> 'confirmed'
  THEN
    RETURN NEW;
  END IF;

  SELECT babysitting_eligible
  INTO sitter_allowed
  FROM staff_members
  WHERE id = NEW.sitter_staff_member_id;

  IF sitter_allowed IS DISTINCT FROM TRUE THEN
    RAISE EXCEPTION
      'STAFF_NOT_BABYSITTING_ELIGIBLE';
  END IF;

  IF TG_OP = 'UPDATE' THEN
    current_request_id := OLD.id;
  ELSE
    current_request_id := NULL;
  END IF;

  PERFORM pg_advisory_xact_lock(
    NEW.sitter_staff_member_id
  );

  IF EXISTS (
    SELECT 1
    FROM babysitting_requests br
    WHERE br.sitter_staff_member_id = NEW.sitter_staff_member_id
      AND br.status = 'confirmed'
      AND (
        current_request_id IS NULL
        OR br.id <> current_request_id
      )
      AND NEW.starts_at < br.ends_at
      AND NEW.ends_at > br.starts_at
  ) THEN
    RAISE EXCEPTION
      'BABYSITTING_TIME_CONFLICT';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM event_activity_staff eas
    JOIN event_activities ea
      ON ea.id = eas.event_activity_id
    WHERE eas.staff_member_id = NEW.sitter_staff_member_id
      AND NEW.starts_at < ea.ends_at
      AND NEW.ends_at > ea.starts_at
  ) THEN
    RAISE EXCEPTION
      'STAFF_ACTIVITY_TIME_CONFLICT';
  END IF;

  RETURN NEW;
END;
$$;


CREATE TRIGGER validate_babysitting_request
BEFORE INSERT OR UPDATE
ON babysitting_requests
FOR EACH ROW
EXECUTE FUNCTION appoponi_validate_babysitting_request();


CREATE OR REPLACE FUNCTION appoponi_validate_babysitting_member()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  request_account_id BIGINT;
  member_account_id BIGINT;
BEGIN
  SELECT er.account_id
  INTO request_account_id
  FROM babysitting_requests br
  JOIN event_registrations er
    ON er.id = br.event_registration_id
  WHERE br.id = NEW.babysitting_request_id;

  SELECT account_id
  INTO member_account_id
  FROM household_members
  WHERE id = NEW.member_id;

  IF request_account_id <> member_account_id THEN
    RAISE EXCEPTION
      'BABYSITTING_MEMBER_WRONG_HOUSEHOLD';
  END IF;

  RETURN NEW;
END;
$$;


